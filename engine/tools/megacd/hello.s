| Hello world payload: loaded from the disc into word RAM by the sub CPU (sp.s) and run there at
| $200000 by the main CPU (ip.s). Clears VRAM, expands our 1-bpp font into tiles, prints two lines.
	.text
	.globl	_start
_start:
	move.w	#0x2700, %sr
	lea	0xC00004, %a0                   | VDP control
	lea	0xC00000, %a1                   | VDP data
	lea	vdpregs(%pc), %a2
1:	move.w	(%a2)+, %d0
	beq.s	2f
	move.w	%d0, (%a0)
	bra.s	1b
2:	move.l	#0x40000000, (%a0)              | clear all 64 KB of VRAM
	move.w	#0x7FFF, %d1
3:	move.w	#0, (%a1)
	dbra	%d1, 3b
	move.l	#0xC0000000, (%a0)              | palette 0: colour 0 dark blue, 1 white, 2 yellow
	move.w	#0x0400, (%a1)
	move.w	#0x0EEE, (%a1)
	move.w	#0x00EE, (%a1)
	move.l	#0x40200000, (%a0)              | tiles from VRAM $0020 (tile 1 = glyph 0)
	lea	font(%pc), %a2
	move.w	#GLYPHS * 8 - 1, %d1
4:	move.b	(%a2)+, %d2                     | one row: 8 pixels, 1 bit each -> 4 bits each
	moveq	#0, %d3
	moveq	#7, %d4
5:	lsl.l	#4, %d3
	lsl.b	#1, %d2
	bcc.s	6f
	addq.l	#1, %d3
6:	dbra	%d4, 5b
	move.l	%d3, (%a1)
	dbra	%d1, 4b
	lea	line1(%pc), %a2
	move.l	#0x46900003, %d0                | plane A $C000 + (y 13 * 64 + x 9) * 2 = $C690
	moveq	#0, %d5                          | palette 0, colour 1
	bsr.s	print
	lea	line2(%pc), %a2
	move.l	#0x48900003, %d0                | row 17
	move.w	#0, %d5
	bsr.s	print
7:	bra.s	7b

| print a line of glyph numbers ($FF ends) at the VRAM write command in d0
print:	move.l	%d0, (%a0)
8:	moveq	#0, %d1
	move.b	(%a2)+, %d1
	cmp.b	#0xFF, %d1
	beq.s	9f
	addq.w	#1, %d1                          | glyph n is tile n + 1 (tile 0 stays blank)
	move.w	%d1, (%a1)
	bra.s	8b
9:	rts

vdpregs:
	.word	0x8004, 0x8144, 0x8230, 0x8407, 0x8578, 0x8700, 0x8B00, 0x8C81
	.word	0x8D3F, 0x8F02, 0x9001, 0x9100, 0x9200, 0
| glyphs, in this order:  0 space  1 A  2 C  3 D  4 E  5 G  6 H  7 I  8 L  9 M
|                        10 O  11 P  12 R  13 S  14 W  15 X  16 Y  17 !  18 ,
	.equ	GLYPHS, 19
font:
