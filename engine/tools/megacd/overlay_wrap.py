#!/usr/bin/env python3
"""overlay_wrap.py RECOMPDIR IMGDIR [VOLATILE]: one compilation unit per generated Mega CD program, so that
programs loaded at the same address (SHCD's stages in Word RAM) link side by side.

For each RECOMPDIR/<NAME>/ (generate.py's output for IMGDIR/<NAME>.bin) writes RECOMPDIR/ov_<NAME>.c:
its generated files #included with every function made static, the registration collected into a
PsOverlay (func_table.h) with the address of every word of every compiled instruction (lengths from
capstone) and the hash of those words in the image (the runtime checks that the same program is in memory before using it), and
RECOMPDIR/ov_all.c: ps_overlays_register() adding them all. Left out of the hash: words the program
writes while it runs - instructions whose opcode word is 0 (ORI.B #n,D0: zeroed variables decoded as
code) and the VOLATILE file's "NAME ADDR" lines (found in replays). Output is generated from the
player's disc: never committed (games/*/src/recomp/ is git-ignored)."""
import os
import re
import sys
from capstone import Cs, CS_ARCH_M68K, CS_MODE_M68K_000

CS = Cs(CS_ARCH_M68K, CS_MODE_M68K_000)


def fnv(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def wrap(recomp, imgdir, name, volatile=frozenset()):
    d = os.path.join(recomp, name)
    files = sorted(f for f in os.listdir(d) if f.endswith('.c') and f not in ('recomp_cycles.c', 'recomp_hooks.c', 'recomp_cheats.c'))
    names, addrs = set(), set()
    for f in files + ['recomp_funcs.h']:
        txt = open(os.path.join(d, f)).read()
        names.update(re.findall(r'^void (\w+)\(void\)', txt, re.M))
        addrs.update(int(a, 16) for a in re.findall(r'ITRACE\(0x([0-9A-Fa-f]+)\)', txt))
    nreg = open(os.path.join(d, 'recomp_funcs.h')).read().count('func_table_register(')
    img = open(os.path.join(imgdir, name + '.bin'), 'rb').read()
    words = set()                    # every word of each instruction: the compiled code has its
    for a in addrs:                  # operands built in, so they must match too
        if img[a:a + 2] == b'\0\0': continue
        ins = next(CS.disasm(img[a:a + 10], a, 1), None)
        words.update(range(a, a + (ins.size if ins else 2), 2))
    addrs = sorted(words - volatile)
    if not addrs: return None        # no code found in it: nothing to wrap
    h = fnv(b''.join(img[a:a + 2] for a in addrs))
    c = name.replace('-', '_')
    out = [f'/* generated by overlay_wrap.py: {name} as an overlay (func_table.h) */',
           '#include <genrecomp/genrecomp.h>', '#include <genrecomp/func_table.h>',
           f'#include "{name}/recomp_common.h"', '']
    out += [f'static void {n}(void);' for n in sorted(names)]
    out += ['', f'static PsOverlayFunc s_f[{nreg}]; static uint32_t s_n;',
            '#define func_table_register(a, f) (s_f[s_n].addr = (a), s_f[s_n++].fn = (f))',
            f'#define recomp_register_all ov_{c}_collect', f'#include "{name}/recomp_funcs.h"',
            '#undef func_table_register']
    out += [f'#include "{name}/{f}"' for f in files]
    out += ['', f'static const uint32_t s_a[{len(addrs)}] = {{']
    out += [','.join(f'0x{a:06X}' for a in addrs[i:i + 12]) + ',' for i in range(0, len(addrs), 12)]
    out += ['};', f'static PsOverlay s_ov = {{ "{name}", 0x{addrs[0]:06X}, 0x{addrs[-1] + 2:06X}, s_a, {len(addrs)}, 0x{h:08X}u, s_f, 0 }};',
            f'void ov_{c}_add(void) {{ ov_{c}_collect(); s_ov.nfuncs = s_n; func_table_add_overlay(&s_ov); }}', '']
    open(os.path.join(recomp, f'ov_{name}.c'), 'w').write('\n'.join(out))
    return c


def main():
    recomp, imgdir = sys.argv[1], sys.argv[2]
    volatile = {}
    if len(sys.argv) > 3 and os.path.exists(sys.argv[3]):
        for l in open(sys.argv[3]):
            f = l.split()
            if len(f) >= 2 and not l.startswith('#'): volatile.setdefault(f[0], set()).add(int(f[1].lstrip('$'), 16))
    done = sorted(n for n in os.listdir(recomp)
                  if os.path.isfile(os.path.join(recomp, n, 'recomp_funcs.h')))
    cs = [c for c in (wrap(recomp, imgdir, n, frozenset(volatile.get(n, ()))) for n in done) if c]
    out = ['/* generated by overlay_wrap.py */']
    out += [f'void ov_{c}_add(void);' for c in cs]
    out += ['void ps_overlays_register(void) {'] + [f'    ov_{c}_add();' for c in cs] + ['}', '']
    open(os.path.join(recomp, 'ov_all.c'), 'w').write('\n'.join(out))
    print(f'{len(cs)} overlays')


if __name__ == '__main__':
    main()
