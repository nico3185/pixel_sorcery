"""pixfont.py: a 5 x 8 pixel font (lower case, digits, . / _ -) for the compilation disc's text - drawn by hand,
legible at the Mega Drive's resolution where scaled TrueType turns 3185 into 31B5. text(s) -> rows of 0/1."""
G = {
 'a': ['', '', '.###.', '....#', '.####', '#...#', '.####', ''],
 'b': ['#....', '#....', '####.', '#...#', '#...#', '#...#', '####.', ''],
 'c': ['', '', '.###.', '#....', '#....', '#....', '.###.', ''],
 'e': ['', '', '.###.', '#...#', '#####', '#....', '.###.', ''],
 'g': ['', '', '.####', '#...#', '#...#', '.####', '....#', '.###.'],
 'h': ['#....', '#....', '####.', '#...#', '#...#', '#...#', '#...#', ''],
 'i': ['..#..', '', '.##..', '..#..', '..#..', '..#..', '.###.', ''],
 'l': ['.##..', '..#..', '..#..', '..#..', '..#..', '..#..', '.###.', ''],
 'm': ['', '', '##.#.', '#.#.#', '#.#.#', '#.#.#', '#...#', ''],
 'n': ['', '', '####.', '#...#', '#...#', '#...#', '#...#', ''],
 'o': ['', '', '.###.', '#...#', '#...#', '#...#', '.###.', ''],
 'p': ['', '', '####.', '#...#', '#...#', '####.', '#....', '#....'],
 'r': ['', '', '#.##.', '##..#', '#....', '#....', '#....', ''],
 's': ['', '', '.####', '#....', '.###.', '....#', '####.', ''],
 't': ['..#..', '..#..', '#####', '..#..', '..#..', '..#..', '...##', ''],
 'u': ['', '', '#...#', '#...#', '#...#', '#..##', '.##.#', ''],
 'x': ['', '', '#...#', '.#.#.', '..#..', '.#.#.', '#...#', ''],
 'y': ['', '', '#...#', '#...#', '#...#', '.####', '....#', '.###.'],
 '0': ['.###.', '#...#', '#..##', '#.#.#', '##..#', '#...#', '.###.', ''],
 '1': ['..#..', '.##..', '..#..', '..#..', '..#..', '..#..', '.###.', ''],
 '2': ['.###.', '#...#', '....#', '...#.', '..#..', '.#...', '#####', ''],
 '3': ['.###.', '#...#', '....#', '..##.', '....#', '#...#', '.###.', ''],
 '5': ['#####', '#....', '####.', '....#', '....#', '#...#', '.###.', ''],
 '6': ['..##.', '.#...', '#....', '####.', '#...#', '#...#', '.###.', ''],
 '7': ['#####', '....#', '...#.', '..#..', '.#...', '.#...', '.#...', ''],
 '8': ['.###.', '#...#', '#...#', '.###.', '#...#', '#...#', '.###.', ''],
 '.': ['', '', '', '', '', '.##..', '.##..', ''],
 '/': ['....#', '....#', '...#.', '..#..', '.#...', '#....', '#....', ''],
 '_': ['', '', '', '', '', '', '', '#####'],
 '-': ['', '', '', '#####', '', '', '', ''],
 ' ': [''] * 8,
}


def text(s):
    """8 rows of 0/1, 6 pixels per character"""
    rows = [[] for _ in range(8)]
    for ch in s:
        g = G[ch]
        for r in range(8):
            line = (g[r] or '').ljust(5, '.')
            rows[r] += [1 if c == '#' else 0 for c in line] + [0]
    return rows
