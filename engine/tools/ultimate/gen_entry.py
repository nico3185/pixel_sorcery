#!/usr/bin/env python3
"""gen_entry.py ID RECOMP_DIR OUT.c [MORE.c...]: the entry of title ID in the multi-title executable (CMakeLists.txt).

The title's code is compiled with its fixed table names renamed ID__name (RENAMED below) and its main
as ID__main; the entry binds the tables the title defines (ps_multi_bind) and runs that main."""
import pathlib, re, sys

RENAMED = ['main', 'ps_m68k_cycles', 'ps_m68k_hook_pc', 'ps_m68k_hook_fn', 'ps_m68k_nhooks', 'ps_z80_game_driver',
           'ps_z80_game_image', 'ps_z80_game_image_len', 'ps_cheat_names', 'ps_cheat_count']


def defined(src, name):
    """name is defined (not only declared) at file scope in one of the title's sources"""
    pat = re.compile(r'^(?!extern|static)[A-Za-z][^;]*[\s*(]' + name + r'\b[^;]*=', re.M)
    return any(pat.search(s) for s in src)


def main():
    tid, rdir, out = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    files = sorted(rdir.glob('*.c')) + [pathlib.Path(x) for x in sys.argv[4:]]   # + generated sources
    src = [p.read_text(errors='replace') for p in files]
    d = {n: defined(src, n) for n in RENAMED[1:]}
    p = tid + '__'
    L = ['/* generated by engine/tools/ultimate/gen_entry.py: title ' + tid + ' */',
         '#include <genrecomp/ps_multi.h>', '#include <stddef.h>',
         'int %smain(int, char **);' % p]
    if d['ps_m68k_cycles']: L.append('extern const uint16_t %sps_m68k_cycles[0x10000];' % p)
    if d['ps_m68k_hook_pc']:
        L.append('extern const uint32_t *%sps_m68k_hook_pc; extern uint32_t (*const *%sps_m68k_hook_fn)(void); '
                 'extern int %sps_m68k_nhooks;' % (p, p, p))
    if d['ps_z80_game_driver']: L.append('extern void (*%sps_z80_game_driver)(void *);' % p)
    if d['ps_z80_game_image']:
        L.append('extern const unsigned char *%sps_z80_game_image; extern unsigned int %sps_z80_game_image_len;' % (p, p))
    if d['ps_cheat_names']: L.append('extern const char *%sps_cheat_names[]; extern int %sps_cheat_count;' % (p, p))
    L += ['int %s_entry(int argc, char **argv) {' % tid, '    PsMultiTitle t = {0};']
    if d['ps_m68k_cycles']: L.append('    t.m68k_cycles = %sps_m68k_cycles;' % p)
    if d['ps_m68k_hook_pc']:
        L.append('    t.hook_pc = %sps_m68k_hook_pc; t.hook_fn = %sps_m68k_hook_fn; t.nhooks = %sps_m68k_nhooks;' % (p, p, p))
    if d['ps_z80_game_driver']: L.append('    t.z80_driver = %sps_z80_game_driver;' % p)
    if d['ps_z80_game_image']:
        L.append('    t.z80_image = %sps_z80_game_image; t.z80_image_len = %sps_z80_game_image_len;' % (p, p))
    if d['ps_cheat_names']: L.append('    t.cheat_names = %sps_cheat_names; t.cheat_count = %sps_cheat_count;' % (p, p))
    L += ['    ps_multi_bind(&t);', '    return %smain(argc, argv);' % p, '}', '']
    text = '\n'.join(L)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == '__main__':
    main()
