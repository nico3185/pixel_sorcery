#!/usr/bin/env python3
"""make_image.py SONIC1 KIS2 OUT - SHK1, step 3: the build-time image.

  SONIC1  the player's SH1 (REV00) dump
  KIS2    the player's SHK + SH2 dump (shk_sh2.bin: SHK2, patch ROM at $300000)
  OUT     the image (git-ignored): SH1 with Knuckles playable

What it does (games/shk1/s2_to_s1.json says what is copied, k1.s is our own code):
  - SH1, unchanged below $80000 except the patch sections of k1.srec (k1.s assembled);
  - k1.srec's shim at $80000;
  - Knuckles' own code from SHK2 (the blocks), relocated at $82000: SH2 engine calls go to
    their SH1 equivalent (directly for jsr/jmp, through a jmp stub for bsr/bra/bcc.w), RAM to
    the SH1 address, plus the listed byte patches;
  - a SH1 animation table in front of SHK2's scripts (S1 animation IDs -> Knuckles scripts);
  - Knuckles' mappings from SHK converted to SH1's format, his DPLC, his art with its colours
    remapped to SH1's line 0, his colours in SH1's palettes (water versions derived);
  - the header's ROM end and checksum.

  --syms FILE   only write k1_reloc.inc (K_<SHK2 address> = relocated address), needs no ROM.
"""
import hashlib, json, os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
CFG = json.load(open(os.path.join(GAME, 's2_to_s1.json')))
H = lambda s: int(s, 16)
L = {k: H(v) for k, v in CFG['layout'].items()}
BLOCKS = [(H(v[0]), H(v[1])) for v in CFG['blocks'].values()]


def layout():
    """SHK2 block -> new address (blocks packed in order at layout.reloc)."""
    out, at = [], L['reloc']
    for lo, hi in BLOCKS:
        out.append((lo, hi, at))
        at += (hi - lo + 1) & ~1
    return out, at


LAY, RELOC_END = layout()


def new(a):
    for lo, hi, at in LAY:
        if lo <= a < hi:
            return at + a - lo
    return None


def block_of(a):
    for i, (lo, hi, _) in enumerate(LAY):
        if lo <= a < hi:
            return i
    return None


def write_syms(path):
    with open(path, 'w') as f:
        f.write('| generated by tools/make_image.py --syms: Knuckles code from SHK2, relocated\n')
        for a in CFG['exports']:
            f.write(f'\t.equ\tK_{H(a):06X},0x{new(H(a)):06X}\n')


def read_srec(path):
    """(address, bytes) runs from an S-record file; the header line carries the k1.s SHA-1."""
    runs, head = [], ''
    for line in open(path):
        line = line.strip()
        if line.startswith('S0'):
            head = bytes.fromhex(line[8:-2]).decode('latin1')
        elif line[:2] in ('S1', 'S2', 'S3'):
            al = {'S1': 2, 'S2': 3, 'S3': 4}[line[:2]]
            n = int(line[2:4], 16)
            addr = int(line[4:4 + 2 * al], 16)
            data = bytes.fromhex(line[4 + 2 * al:2 + 2 * n])   # without the checksum byte
            runs.append((addr, data))
    return runs, head


def main():
    a = sys.argv[1:]
    if a and a[0] == '--syms':
        write_syms(a[1]); return
    s1p, k2p, outp = a[:3]
    s1, k2 = open(s1p, 'rb').read(), open(k2p, 'rb').read()
    for name, data, want in (('SH1', s1, CFG['sh1_sha1']), ('SHK2', k2, CFG['shk2_sha1'])):
        got = hashlib.sha1(data).hexdigest()
        if got != want:
            sys.exit(f'{name}: SHA-1 {got}, expected {want} (SH1 REV00 / SHK + SH2 World dump)')
    img = bytearray(s1) + bytes(L['size'] - len(s1))
    k2 = bytearray(k2)

    # --- our code: k1.srec (k1.s assembled); stale-check against k1.s
    srec = os.path.join(GAME, 'k1.srec')
    runs, head = read_srec(srec)
    want = hashlib.sha1(open(os.path.join(GAME, 'k1.s'), 'rb').read()).hexdigest()[:16]
    if want not in head:
        sys.exit('k1.srec is older than k1.s: run tools/build_shim.sh (needs m68k-elf binutils)')
    syms = {}
    for line in open(os.path.join(GAME, 'k1.sym')):
        v, t, n = line.split()
        syms[n] = int(v, 16)

    # --- relocate SHK2 blocks
    for p in CFG['patches']:
        at, nb = H(p['at']), bytes.fromhex(p['new'])
        k2[at:at + len(nb)] = nb
    dead = [(H(d[0]), H(d[1])) for d in CFG['dead']] + [(H(d[0]), H(d[1])) for d in CFG['data']]
    for p in CFG['patches']:   # a patched bra.s makes the skipped bytes dead
        nb = bytes.fromhex(p['new'])
        if len(nb) == 2 and nb[0] == 0x60 and nb[1]:
            at = H(p['at']); dead.append((at + 2, at + 2 + nb[1]))
    calls = {H(k): (syms[v[0]] if v[0] in syms else H(v[0])) for k, v in CFG['calls'].items()}
    ram = {H(k): H(v[0]) for k, v in CFG['ram'].items()}
    for lo, hi, at in LAY:
        img[at:at + hi - lo] = k2[lo:hi]
    stubs, stub_at = {}, RELOC_END

    def stub(target):
        nonlocal stub_at
        if target not in stubs:
            stubs[target] = stub_at
            img[stub_at:stub_at + 6] = b'\x4e\xf9' + struct.pack('>I', target)
            stub_at += 6
        return stubs[target]

    import capstone
    md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_BIG_ENDIAN | capstone.CS_MODE_M68K_000)
    problems = []
    for lo, hi, at in LAY:
        pc = lo
        while pc < hi:
            d = [x for x in dead if x[0] <= pc < x[1]]
            if d:
                pc = d[0][1]; continue
            ins = next(md.disasm(bytes(k2[pc:pc + 10]), pc), None)
            if ins is None:
                problems.append(f'${pc:06X}: cannot decode'); break
            npc = new(pc)
            op = struct.unpack('>H', k2[pc:pc + 2])[0]
            b = bytes(k2[pc:pc + ins.size])
            ops = ins.op_str

            def put(off, fmt, v):
                img[npc + off:npc + off + struct.calcsize(fmt)] = struct.pack(fmt, v)

            if (op & 0xF000) == 0x6000 or (op & 0xF0F8) == 0x50C8:      # Bcc/BRA/BSR, DBcc
                db = (op & 0xF0F8) == 0x50C8
                d8 = op & 0xFF
                short = not db and d8 not in (0, 0xFF)
                disp = (d8 - 256 if d8 > 127 else d8) if short else struct.unpack('>h', b[2:4])[0]
                t = pc + 2 + disp
                nt = new(t)
                if nt is None:
                    if t not in calls:
                        problems.append(f'${pc:06X} {ins.mnemonic} {ops}: target ${t:06X} not mapped')
                        pc += ins.size; continue
                    nt = stub(calls[t])
                nd = nt - (npc + 2)
                if short:
                    if not -128 <= nd < 128:
                        problems.append(f'${pc:06X}: short branch out of reach after relocation')
                    img[npc + 1] = nd & 0xFF
                else:
                    if not -32768 <= nd < 32768:
                        problems.append(f'${pc:06X}: branch out of reach')
                    put(2, '>h', nd)
            elif op in (0x4EB9, 0x4EF9):                                 # jsr/jmp abs.l
                t = struct.unpack('>I', b[2:6])[0]
                nt = new(t) if new(t) is not None else calls.get(t)
                if nt is None:
                    problems.append(f'${pc:06X} {ins.mnemonic} ${t:06X}: not mapped')
                else:
                    put(2, '>I', nt)
            else:
                for v, sz in re.findall(r'\$([0-9a-f]+)\.([wl])', ops):
                    x = int(v, 16)
                    if sz == 'w':
                        if x < 0x8000:
                            continue
                        full = 0xFF0000 | x
                        if full not in ram:
                            problems.append(f'${pc:06X} {ins.mnemonic} {ops}: RAM ${full:06X} not mapped')
                            continue
                        pat = struct.pack('>H', x)
                        i = b.find(pat, 2)
                        if i < 0 or b.find(pat, i + 1) >= 0:
                            problems.append(f'${pc:06X}: RAM operand not unique'); continue
                        put(i, '>H', ram[full] & 0xFFFF)
                    else:
                        pat = struct.pack('>I', x)
                        i = b.find(pat, 2)
                        nt = new(x)
                        if x >= 0xFF0000:
                            nt = ram.get(x)
                        if nt is None or i < 0:
                            problems.append(f'${pc:06X} {ins.mnemonic} {ops}: ${x:06X} not mapped')
                            continue
                        put(i, '>I', nt)
                m = re.search(r'\$([0-9a-f]+)\(pc', ops)
                if m:
                    t = int(m.group(1), 16)
                    if block_of(t) != block_of(pc):
                        problems.append(f'${pc:06X}: pc-relative reference to another block')
                for v in re.findall(r'#\$([0-9a-f]+)', ops):     # ROM pointers as immediates
                    x = int(v, 16)
                    if 0x200000 <= x < 0x340000 and len(v) >= 6:
                        problems.append(f'${pc:06X} {ins.mnemonic} {ops}: ROM pointer immediate')
            pc += ins.size
    if problems:
        sys.exit('relocation problems:\n  ' + '\n  '.join(problems))

    # --- SH1 animation table in front of nothing else: after the stubs
    lea_at = new(H(CFG['blocks']['animate'][0]))
    old_tab = struct.unpack('>I', k2[H(CFG['blocks']['animate'][0]) + 2:H(CFG['blocks']['animate'][0]) + 6])[0]
    tab = (stub_at + 1) & ~1
    for i, kid in enumerate(CFG['animations']['map']):
        script = old_tab + struct.unpack('>H', k2[old_tab + 2 * H(kid):old_tab + 2 * H(kid) + 2])[0]
        img[tab + 2 * i:tab + 2 * i + 2] = struct.pack('>h', new(script) - tab)
    img[lea_at + 2:lea_at + 6] = struct.pack('>I', tab)
    end = tab + 2 * len(CFG['animations']['map'])
    if end > L['maps'] or syms.get('K_VBDMA', 0) >= L['reloc']:
        sys.exit('layout overflow')

    # --- mappings (SHK: word count, 6-byte pieces) -> SH1 (byte count, 5-byte pieces)
    P = CFG['palette']
    nfr, maps = P['frames'], H(P['maps'])
    w = lambda d, a: struct.unpack('>H', d[a:a + 2])[0]
    body, offs = bytearray(), []
    for f in range(nfr):
        offs.append(2 * nfr + len(body))
        src = maps + w(k2, maps + 2 * f)
        n = w(k2, src)
        body.append(n)
        for i in range(n):
            p = src + 2 + 6 * i
            x = struct.unpack('>h', k2[p + 4:p + 6])[0]
            assert -128 <= x < 128
            body += k2[p:p + 4] + struct.pack('>b', x)
    # frames $80+ are reached from entry $80 (SH1's BuildSprites doubles frames with add.b; K_DPLC
    # points the object at K_MAP+$100 for them), so their offsets are relative to that entry
    offs = [o - (0x100 if f >= 0x80 else 0) for f, o in enumerate(offs)]
    blob = b''.join(struct.pack('>H', o) for o in offs) + body
    img[L['maps']:L['maps'] + len(blob)] = blob
    if L['maps'] + len(blob) > L['dplc']:
        sys.exit('mappings overflow')

    # --- DPLC (kept in SHK format, read by K_DPLC) and the art tiles it uses
    dp = H(P['dplc'])
    dend, maxtile = 2 * nfr, 0
    for f in range(nfr):
        o = w(k2, dp + 2 * f)
        n = w(k2, dp + o)
        dend = max(dend, o + 2 + 2 * n)
        for i in range(n):
            e = w(k2, dp + o + 2 + 2 * i)
            maxtile = max(maxtile, (e & 0xFFF) + (e >> 12) + 1)
    img[L['dplc']:L['dplc'] + dend] = k2[dp:dp + dend]
    if L['dplc'] + dend > L['art'] or 32 * maxtile > 0x20000:
        sys.exit('DPLC/art overflow')

    # colours. Default: no SH1 palette entry changes - every Knuckles colour (SHK2's line 0,
    # SH2 slot layout) is drawn with the nearest colour SH1's line 0 already has, Sonic's
    # blues (slots 2-5) excepted, so enemies and objects keep SH1's colours. K_ART2: the
    # "KNUCKLES COLOURS" option - his own colours in slots 2-5 (written into the palette buffers
    # at run time by K_ColSync from PALTAB), his slots 14/15 on the nearest SH1 colour.
    kpal = [w(k2, H(P['knuckles']) + 2 * i) for i in range(16)]
    s1pal = [w(img, 0x2388 + 2 * i) for i in range(16)]
    rgb = lambda c: ((c >> 1) & 7, (c >> 5) & 7, (c >> 9) & 7)
    dist = lambda a, b: sum((x - y) ** 2 for x, y in zip(rgb(a), rgb(b)))
    slot_d = [0] + [min([1] + list(range(6, 16)), key=lambda t: dist(kpal[s], s1pal[t])) for s in range(1, 16)]
    target = list(s1pal); target[2:6] = kpal[2:6]
    slot = list(range(16))
    for s in (14, 15):
        slot[s] = min(range(2, 16), key=lambda t: dist(kpal[s], target[t]))
    rm = H(P['remap'])
    art = H(P['art'])
    for base, sl in ((L['art'], slot_d), (L['art2'], slot)):
        lut = bytes((sl[k2[rm + i] >> 4] << 4) | sl[k2[rm + i] & 15] for i in range(256))
        img[base:base + 32 * maxtile] = bytes(lut[c] for c in k2[art:art + 32 * maxtile])
    remap_d = lambda data: bytes((slot_d[b >> 4] << 4) | slot_d[b & 15] for b in data)

    # PALTAB (K_ColSync): SH1's slots 2-5 of each palette Knuckles appears in -> his colours
    # (water versions shifted the way SH1 shifts Sonic's); count-1, then 4 + 4 words per entry
    pairs = []
    def add(s1w, kw):
        if (s1w, kw) not in pairs:
            pairs.append((s1w, kw))
    for d in P['dry']:
        add(tuple(w(s1, H(d) + 2 * i) for i in range(2, 6)), tuple(kpal[2:6]))
    for wet, dry in P['wet']:
        wa, da = H(wet), H(dry)
        kw = []
        for i in range(2, 6):
            sd, sw = rgb(w(s1, da + 2 * i)), rgb(w(s1, wa + 2 * i))
            k = rgb(kpal[i])
            c = [max(0, min(7, k[j] + sw[j] - sd[j])) for j in range(3)]
            kw.append((c[0] << 1) | (c[1] << 5) | (c[2] << 9))
        add(tuple(w(s1, wa + 2 * i) for i in range(2, 6)), tuple(kw))
    pt = L['paltab']
    img[pt:pt + 2] = struct.pack('>H', len(pairs) - 1)
    for n_, (a_, b_) in enumerate(pairs):
        img[pt + 2 + 16 * n_:pt + 18 + 16 * n_] = struct.pack('>8H', *a_, *b_)

    # --- HUD lives icon: SHK2's (Knuckles' face, "K.T.E"), on SH1's colours, Nemesis-recompressed
    # after the DPLC, SH1's PLC entry pointed at it
    sys.path.insert(0, HERE); import nemesis       # its sibling (python -I leaves the script dir out)
    hud = CFG['hud']
    tiles, _ = nemesis.decode(k2, H(hud['lives_shk2']))
    tiles = remap_d(tiles)
    packed = nemesis.encode(tiles)
    at = (L['dplc'] + dend + 1) & ~1
    if len(packed) > 0x1000 - 2 or nemesis.decode(packed)[0] != tiles:
        sys.exit('lives icon')
    img[at:at + len(packed)] = packed
    img[H(hud['lives_plc']):H(hud['lives_plc']) + 4] = struct.pack('>I', at)
    # signpost: SH1's art with SHK2's Knuckles face over Sonic's
    sign, _ = nemesis.decode(s1, H(hud['sign_s1_art']))
    face, _ = nemesis.decode(k2, H(hud['sign_shk2_face']))
    face = remap_d(face)
    ft = H(hud['sign_face_tile'])
    sign = sign[:32 * ft] + face + sign[32 * ft + len(face):]
    packed = nemesis.encode(sign)
    at = (L['dplc'] + dend + 0x1000) & ~1
    if at + len(packed) > L['art'] or nemesis.decode(packed)[0] != sign:
        sys.exit('signpost')
    img[at:at + len(packed)] = packed
    img[H(hud['sign_s1_plc']):H(hud['sign_s1_plc']) + 4] = struct.pack('>I', at)
    # 1-up monitor icon: Knuckles' face from the lives icon (its first 2x2 tiles, the same layout
    # as the monitor icons) over Sonic's in SH1's monitor art
    mon, _ = nemesis.decode(s1, H(hud['mon_s1_art']))
    mt = H(hud['mon_face_tile'])
    mon = mon[:32 * mt] + tiles[:4 * 32] + mon[32 * mt + 4 * 32:]
    packed = nemesis.encode(mon)
    at = (L['dplc'] + dend + 0x2000) & ~1
    if at + len(packed) > L['art'] or nemesis.decode(packed)[0] != mon:
        sys.exit('monitor')
    img[at:at + len(packed)] = packed
    img[H(hud['mon_s1_plc']):H(hud['mon_s1_plc']) + 4] = struct.pack('>I', at)

    # act results "KNUCKLES HAS", special stage "KNUCKLES GOT THEM ALL": SH1's title-card font
    # (letter -> first tile; I is 8 wide), each text a new frame in a copy of its mapping table
    font, t = {}, 0
    for ch in 'ABCDEFGHIKLMNOPRSTUYZ':
        font[ch] = t; t += 2 if ch == 'I' else 4
    def text_frame(text, space, old):
        # centred where the frame it replaces was centred
        xs = [(struct.unpack('b', old[1 + 5 * i + 4:1 + 5 * i + 5])[0], 8 * (((old[1 + 5 * i + 1] >> 2) & 3) + 1))
              for i in range(old[0])]
        centre = (min(x for x, _ in xs) + max(x + wd for x, wd in xs)) // 2
        widths = [space if c == ' ' else (8 if c == 'I' else 16) for c in text]
        x, pieces = centre - sum(widths) // 2, []
        for c, wd in zip(text, widths):
            if c != ' ':
                pieces.append(struct.pack('>bBHb', -8, 0x1 if c == 'I' else 0x5, font[c], x))
            x += wd
        return bytes([len(pieces)]) + b''.join(pieces)
    for t_ in hud['texts']:
        rm_, nfr_ = H(t_['map']), t_['frames']
        frames_ = []
        for f in range(nfr_):          # offsets are signed: some frames are another table's
            a = rm_ + struct.unpack('>h', s1[rm_ + 2 * f:rm_ + 2 * f + 2])[0]
            old_ = s1[a:a + 1 + 5 * s1[a]]
            frames_.append(text_frame(t_['text'], t_['space'], old_) if f == t_['frame'] else old_)
        tab_, off_ = bytearray(), 2 * nfr_
        for fr in frames_:
            tab_ += struct.pack('>H', off_); off_ += len(fr)
        ra = H(t_['at'])
        img[ra:ra + off_] = tab_ + b''.join(frames_)
        img[H(t_['ptr']):H(t_['ptr']) + 4] = struct.pack('>I', ra)

    # --- title (SHK2 style): Knuckles in TitleSonic's place, the banner as a fifth Obj0F frame
    T = CFG['title']
    tb = H(T['base'])
    def put_blob(off, blob, room):
        if len(blob) > room:
            sys.exit(f'title data overflow at +{off:#x}')
        img[tb + off:tb + off + len(blob)] = blob
    # Knuckles on SH1's title line 1 as it is (no palette change): each of his colours (SHK2's
    # title line 0) drawn with the nearest line-1 colour, Sonic's blues (slots 1-5) excepted
    kp = [w(k2, H(T['knux_pal']) + 2 * i) for i in range(16)]
    p1 = H(T['s1_title_pal1'])
    l1 = [w(s1, p1 + 2 * i) for i in range(16)]
    knib = {0: 0}
    for kidx in range(1, 16):
        knib[kidx] = min(range(6, 16), key=lambda t: dist(kp[kidx], l1[t]))
    t0, t1 = H(T['knux_tiles'][0]), H(T['knux_tiles'][1])
    ktiles, _ = nemesis.decode(k2, H(T['knux_art']))
    ktiles = bytes((knib[b >> 4] << 4) | knib[b & 15] for b in ktiles[32 * t0:32 * t1])
    put_blob(0, nemesis.encode(ktiles), 0x1800)
    km = H(T['knux_map'])
    def sh3k_frame(addr):
        n = w(k2, addr)
        return [(struct.unpack('b', k2[addr + 2 + 6 * i:addr + 3 + 6 * i])[0], k2[addr + 3 + 6 * i],
                 w(k2, addr + 4 + 6 * i), struct.unpack('>h', k2[addr + 6 + 6 * i:addr + 8 + 6 * i])[0]) for i in range(n)]
    kf = {f: sh3k_frame(km + w(k2, km + 2 * f)) for f in T['knux_frames']}
    body = kf[4] + kf[5]
    xmax = max(x + 8 * (((s >> 2) & 3) + 1) for y, s, t, x in body)
    ymax = max(y + 8 * ((s & 3) + 1) for y, s, t, x in body)
    dx = 116 - 112                     # SHK2's place for him (emblem centred at x 160 in both)
    dy = (118 + 32) - (22 + 32) - ymax  # his feet where Sonic's are, all 32 lines lower
    def s1_frame(pieces, ddx, ddy, tilefix):
        out = bytearray([len(pieces)])
        for y, s, t, x in pieces:
            y, x = y + ddy, x + ddx
            assert -128 <= y < 128 and -128 <= x < 128, (y, x)
            out += struct.pack('>bBHb', y, s, tilefix(t), x)
        return out
    kfix = lambda t: (t & 0xF800) | ((t & 0x7FF) - t0)
    n = T['s1_tson_frames']
    frames = [s1_frame(kf[4] + kf[5 if f < 6 else (6 if f == 6 else 7)], dx, dy, kfix) for f in range(n)]
    tab = bytearray()
    off = 2 * n
    for fr in frames:
        tab += struct.pack('>H', off); off += len(fr)
    put_blob(0x4000, tab + b''.join(frames), 0x800)
    # banner: SHK2 line 3 is S1's title line 0 but for black (1 -> 15); tiles to banner_vram_tile
    bt = H(T['banner_vram_tile'])
    for i, (src, tile) in enumerate(T['banner_art']):
        tl, _ = nemesis.decode(k2, H(src))
        tl = bytes(((15 if b >> 4 == 1 else b >> 4) << 4) | (15 if b & 15 == 1 else b & 15) for b in tl)
        put_blob(0x1800 + 0x2000 * i, nemesis.encode(tl), 0x2000 if i == 0 else 0x800)
    bfix = lambda t: 0x8000 | (t & 0x1800) | ((t & 0x7FF) - H(T['banner_art'][0][1]) + bt - 0x200)
    banner = s1_frame(sh3k_frame(H(T['banner_frame'])), 0, 0, bfix)
    psb = H(T['s1_psb_map'])
    nps = w(s1, psb) // 2
    old = [s1[psb + w(s1, psb + 2 * f):psb + w(s1, psb + 2 * f) + 1 + 5 * s1[psb + w(s1, psb + 2 * f)]] for f in range(nps)]
    tab, off = bytearray(), 2 * (nps + 1)
    for fr in old + [banner]:
        tab += struct.pack('>H', off); off += len(fr)
    put_blob(0x4800, tab + b''.join(old) + banner, 0x800)

    # --- our code over SH1, then the shim
    for addr, data in runs:
        img[addr:addr + len(data)] = data

    # --- header: ROM end, checksum (SH1 sums words from $200 to the end)
    img[0x1A4:0x1A8] = struct.pack('>I', len(img) - 1)
    ck = sum(struct.unpack(f'>{(len(img) - 0x200) // 2}H', img[0x200:])) & 0xFFFF
    img[0x18E:0x190] = struct.pack('>H', ck)
    open(outp, 'wb').write(img)
    print(f'{outp}: {len(img) // 1024} KB; Knuckles code {RELOC_END - L["reloc"]} bytes from {len(LAY)} blocks, '
          f'{len(stubs)} stubs, {nfr} frames, {maxtile} art tiles, default colours {slot_d[1:]}')


